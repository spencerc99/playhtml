-- ABOUTME: Adds documents_staging, the room document table the staging real-time server reads and writes.
-- ABOUTME: Keeps staging traffic out of the production documents table while sharing one project.

-- Same columns as public.documents, plus the two the v2 operation protocol
-- stores: the room snapshot as JSON and the protocol version that owns the room.
-- A room starts empty here; rooms are copied in from public.documents on purpose.
CREATE TABLE public.documents_staging (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamp with time zone NOT NULL DEFAULT now(),
  document text,
  name text,
  document_json jsonb,
  protocol_version integer NOT NULL DEFAULT 1,
  CONSTRAINT documents_staging_name_key UNIQUE (name)
);

-- Only the server's service role reads or writes room documents. Row level
-- security with no policies blocks every other role, and the grants below
-- remove the table privileges new public tables get by default.
ALTER TABLE public.documents_staging ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE public.documents_staging FROM anon, authenticated;
GRANT ALL ON TABLE public.documents_staging TO service_role;
